// 入力される値:価格 税率
// 戻す値:　税込価格
// 計算手順:　価格に1+税率をかける

/**
 * 商品の税込価格を返す。
 *
 * @param {number} price
 * @param {number} taxRate
 * @returns {number}
 */
function calculatePriceWithTax(price, taxRate) {
  // ここに実装してください。
  return price * (1 + taxRate);
}

